#!/usr/bin/env node
/**
 * Writes src/lib/pose/rig3d-skeleton.ts from the 3D pose bodies (public/pose-3d/body-*.glb) and
 * their face landmarks (landmarks-*.json, written by build_rig.py): each bone's rest transform,
 * so the pose maths (forward kinematics, the OpenPose projection, lifting) runs without WebGL
 * and without loading the GLB — in unit tests and before the body has downloaded.
 *
 *   node scripts/pose-3d/skeleton.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Matrix4 } from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';

const ROOT = new URL('../..', import.meta.url).pathname;
const round = v => Math.round(v * 1e5) / 1e5;

async function readBody(kind) {
  const buf = readFileSync(join(ROOT, 'public/pose-3d', `body-${kind}.glb`));
  const ab = buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength);
  const gltf = await new Promise((resolve, reject) =>
    new GLTFLoader().parse(ab, '', resolve, reject)
  );
  const bones = [];
  gltf.scene.updateMatrixWorld(true);
  gltf.scene.traverse(node => {
    if (!node.isBone) return;
    if (!node.parent?.isBone) {
      // The armature node above the hips must be identity: the maths places the hips in world.
      const m = node.parent.matrixWorld;
      if (!m.equals(new Matrix4())) throw new Error(`${kind}: armature node is not identity`);
    }
    bones.push({
      name: node.name,
      parent: node.parent?.isBone ? node.parent.name : null,
      p: node.position.toArray().map(round),
      q: node.quaternion.toArray().map(round),
    });
  });
  const marks = JSON.parse(
    readFileSync(join(ROOT, 'scripts/pose-3d', `landmarks-${kind}.json`), 'utf8')
  );
  const landmarks = {
    nose: marks.nose,
    eyeR: marks.eye_R,
    eyeL: marks.eye_L,
    earR: marks.ear_R,
    earL: marks.ear_L,
  };
  return { bones, landmarks };
}

const female = await readBody('female');
const male = await readBody('male');
const body = data => JSON.stringify(data, null, 2);
writeFileSync(
  join(ROOT, 'src/lib/pose/rig3d-skeleton.ts'),
  `/**
 * The 3D pose bodies' skeletons at rest (glTF y-up metres; the figure faces +z, its left is +x):
 * each bone's rest position and rotation in its parent's space, and the face landmarks (nose,
 * eyes, ears) in world space at rest. Generated by scripts/pose-3d/skeleton.mjs from
 * public/pose-3d/body-*.glb — do not edit by hand.
 */

export type Rig3dBoneRest = {
  name: string;
  parent: string | null;
  p: [number, number, number];
  q: [number, number, number, number];
};

export type Rig3dSkeleton = {
  bones: Rig3dBoneRest[];
  landmarks: Record<'nose' | 'eyeR' | 'eyeL' | 'earR' | 'earL', [number, number, number]>;
};

export const RIG3D_SKELETONS: Record<'female' | 'male', Rig3dSkeleton> = {
  female: ${body(female)},
  male: ${body(male)},
};
`
);
console.log('wrote src/lib/pose/rig3d-skeleton.ts', female.bones.length, 'bones');
