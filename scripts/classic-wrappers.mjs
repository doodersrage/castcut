// @ts-check
/**
 * The classic Prompt Studio app's route files: thin wrappers that re-export a shared route, with
 * its route segment config copied as written (Next reads that statically). Plain JavaScript with
 * no imports: Castcut's generator (src/lib/classic-app.ts) and the core package's
 * `prompt-studio-sync-routes` (scripts/core-sync-routes.mjs) both use it.
 * docs/architecture-boundaries.md.
 */

export const CLASSIC_GENERATED_MARK = '// Generated by scripts/gen-classic-app.mts';

/** Segment config Next reads statically: copied as written (single-line `export const`). */
const SEGMENT_CONFIG_RE =
  /^export const (?:runtime|maxDuration|dynamic|revalidate|fetchCache|dynamicParams|preferredRegion|size|contentType|alt)\b[^\n]*;$/gm;

/** The proxy's `config` (matcher) block. */
const PROXY_CONFIG_RE = /^export const config = \{[\s\S]*?\n\};$/m;

/**
 * @param {string} sourcePath the shared file, `src/...`
 * @param {string} source its contents
 * @param {string} [importPrefix] where `src/` is imported from — `@/` in Castcut, the core
 *   package's `src/` in the standalone Prompt Studio repo
 * @returns {string}
 */
export function wrapperSource(sourcePath, source, importPrefix = '@/') {
  const spec = importPrefix + sourcePath.replace(/^src\//, '').replace(/\.(?:ts|tsx)$/, '');
  const client = /^\s*['"]use client['"]/.test(source);
  const hasDefault = /^export default\b/m.test(source);
  const lines = [CLASSIC_GENERATED_MARK + ` from ${sourcePath} — do not edit.`];
  if (client) {
    // A client module can only be re-exported by name.
    lines.unshift("'use client';", '');
    if (hasDefault) lines.push(`export { default } from '${spec}';`);
    return lines.join('\n') + '\n';
  }
  const config = [...source.matchAll(SEGMENT_CONFIG_RE)].map(match => match[0]);
  const proxyConfig = PROXY_CONFIG_RE.exec(source)?.[0];
  if (proxyConfig) config.push(proxyConfig);
  lines.push(...config);
  if (proxyConfig) {
    // Next looks for a `proxy` function declared in the file itself.
    lines.push(
      "import type { NextRequest } from 'next/server';",
      `import { proxy as sharedProxy } from '${spec}';`,
      'export function proxy(request: NextRequest) {',
      '  return sharedProxy(request);',
      '}'
    );
    return lines.join('\n') + '\n';
  }
  lines.push(`export * from '${spec}';`);
  if (hasDefault) lines.push(`export { default } from '${spec}';`);
  return lines.join('\n') + '\n';
}
