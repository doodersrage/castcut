import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { after, before, describe, it } from 'node:test';
import {
  comfyInputDir,
  comfyInstallIdentity,
  comfyRootForModelsDir,
  modelsDirFromModelPaths,
  parseComfyInstallInfo,
} from './install-info';
import { COMFY_NODE_PACKS, comfyNodePackState, managerInstalledNames } from './node-pack-catalog';

const DESKTOP_STATS = {
  system: {
    os: 'linux',
    comfyui_version: '0.42.5',
    python_version: '3.13.12 (main) [Clang]',
    embedded_python: false,
    deploy_environment: 'local-desktop2-standalone',
    argv: [
      'ComfyUI/main.py',
      '--listen',
      '0.0.0.0',
      '--extra-model-paths-config',
      '/home/u/.local/share/comfyui-desktop-2/inst.yaml',
      '--input-directory',
      '/home/u/ComfyUI-Shared/input',
      '--output-directory=/home/u/ComfyUI-Shared/output',
    ],
  },
  devices: [{ name: 'cuda:0 NVIDIA GeForce RTX 4090 : cudaMallocAsync' }],
};

const DESKTOP_YAML = `# Generated by Comfy Desktop
comfy.desktop_0:
  base_path: '/home/u/ComfyUI-Shared/models'
  is_default: true
  'checkpoints': 'checkpoints/'
  'controlnet': |-
    controlnet/
    t2i_adapter/
  'loras': 'loras/'
`;

describe('which ComfyUI install answers', () => {
  it('reads the desktop app’s folders from its start-up arguments and model-paths file', () => {
    const info = parseComfyInstallInfo(DESKTOP_STATS)!;
    assert.equal(info.version, '0.42.5');
    assert.equal(info.python, '3.13.12');
    assert.equal(info.gpu, 'NVIDIA GeForce RTX 4090');
    assert.equal(comfyInputDir(info), '/home/u/ComfyUI-Shared/input');
    assert.equal(info.outputDir, '/home/u/ComfyUI-Shared/output');
    assert.deepEqual(info.modelPathFiles, ['/home/u/.local/share/comfyui-desktop-2/inst.yaml']);
    const models = modelsDirFromModelPaths(DESKTOP_YAML);
    assert.equal(models, '/home/u/ComfyUI-Shared/models');
    // Downloads write <root>/models/…: the root is the folder holding "models".
    assert.equal(comfyRootForModelsDir(models), '/home/u/ComfyUI-Shared');
  });

  it('reads ComfyUI’s own example layout and a plain install beside main.py', () => {
    assert.equal(
      modelsDirFromModelPaths(
        'comfyui:\n  base_path: /opt/ComfyUI/\n  is_default: true\n  checkpoints: models/checkpoints/\n'
      ),
      '/opt/ComfyUI/models'
    );
    const plain = parseComfyInstallInfo({ system: { argv: ['/opt/ComfyUI/main.py'] } })!;
    assert.equal(comfyInputDir(plain), '/opt/ComfyUI/input');
    // A relative main.py (the desktop app) says nothing about where it runs.
    assert.equal(
      comfyInputDir(parseComfyInstallInfo({ system: { argv: ['ComfyUI/main.py'] } })!),
      undefined
    );
    assert.equal(comfyRootForModelsDir('/mnt/models-elsewhere/checkpoints'), undefined);
  });

  it('keeps an install’s identity through a version update, not through a switch', () => {
    const info = parseComfyInstallInfo(DESKTOP_STATS)!;
    const upgraded = parseComfyInstallInfo({
      ...DESKTOP_STATS,
      system: { ...DESKTOP_STATS.system, comfyui_version: '0.43.0' },
    })!;
    assert.equal(comfyInstallIdentity(info, '/m'), comfyInstallIdentity(upgraded, '/m'));
    const other = parseComfyInstallInfo({ system: { argv: ['/opt/comfyui/main.py'] } })!;
    assert.notEqual(comfyInstallIdentity(info, '/m'), comfyInstallIdentity(other));
  });
});

describe('node packs', () => {
  const face = COMFY_NODE_PACKS.find(pack => pack.id === 'faceAnalysis')!;

  it('tells loaded, installed-but-not-loading and missing apart', () => {
    const installed = managerInstalledNames({
      'ComfyUI_FaceAnalysis': { enabled: true },
      'some/other-pack': { cnr_id: 'other-pack' },
      disabled: { enabled: false, cnr_id: 'comfyui_controlnet_aux' },
    });
    assert.ok(installed?.has('comfyui_faceanalysis'));
    assert.equal(installed?.has('comfyui_controlnet_aux'), false);
    assert.equal(
      comfyNodePackState(face, new Set(['FaceAnalysisModels', 'FaceEmbedDistance']), installed),
      'loaded'
    );
    // In custom_nodes, nodes not in object_info: its import failed (InsightFace, usually).
    assert.equal(comfyNodePackState(face, new Set(), installed), 'not-loading');
    assert.equal(comfyNodePackState(face, new Set(), new Set()), 'missing');
    // The Manager could not be asked: broken and never-installed look the same.
    assert.equal(comfyNodePackState(face, new Set(), null), 'unknown');
  });
});

describe('the assistant’s memory and jobs', () => {
  let dataDir = '';
  let previousDataDir: string | undefined;
  let previousRoot: string | undefined;
  before(() => {
    dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'comfy-install-'));
    previousDataDir = process.env.PROMPT_DATA_DIR;
    previousRoot = process.env.COMFYUI_ROOT;
    process.env.PROMPT_DATA_DIR = dataDir;
  });
  after(() => {
    if (previousDataDir === undefined) delete process.env.PROMPT_DATA_DIR;
    else process.env.PROMPT_DATA_DIR = previousDataDir;
    if (previousRoot === undefined) delete process.env.COMFYUI_ROOT;
    else process.env.COMFYUI_ROOT = previousRoot;
    fs.rmSync(dataDir, { recursive: true, force: true });
  });

  it('notices a switch, remembers the previous install, and is told when it is set up', async () => {
    const store = await import('./install-store-server');
    const record = (identity: string, seenAt: number) => ({
      identity,
      seenAt,
      info: { modelPathFiles: [] },
      inputDir: `/${identity}/input`,
    });
    // The first install the app sees needs no notice.
    let entry = store.noteComfyInstall('http://c:8188', record('old', 1));
    assert.equal(entry.acknowledged, 'old');
    entry = store.noteComfyInstall('http://c:8188/', record('new', 2));
    assert.equal(entry.current?.identity, 'new');
    assert.equal(entry.previous?.inputDir, '/old/input');
    assert.notEqual(entry.acknowledged, 'new');
    store.acknowledgeComfyInstall('http://c:8188', 'new');
    assert.equal(store.loadComfyInstallStore().installs['http://c:8188']?.acknowledged, 'new');
  });

  it('downloads go to the folder chosen in the assistant over COMFYUI_ROOT', async () => {
    const { getComfyUiRoot } = await import('./comfy-asset-paths');
    const store = await import('./install-store-server');
    process.env.COMFYUI_ROOT = '/opt/old-comfyui';
    assert.equal(getComfyUiRoot(), path.resolve('/opt/old-comfyui'));
    store.setSavedComfyRoot('/home/u/ComfyUI-Shared');
    assert.equal(getComfyUiRoot(), path.resolve('/home/u/ComfyUI-Shared'));
    // A test's own env is asked about alone.
    assert.equal(getComfyUiRoot({ COMFYUI_ROOT: '/x' } as unknown as NodeJS.ProcessEnv), path.resolve('/x'));
    store.setSavedComfyRoot(null);
    assert.equal(getComfyUiRoot(), path.resolve('/opt/old-comfyui'));
  });

  it('falls back to the ComfyUI running on this machine when COMFYUI_ROOT is unset or gone', async () => {
    const { resolveComfyUiRoot } = await import('./comfy-asset-paths');
    const store = await import('./install-store-server');
    const shared = path.join(dataDir, 'ComfyUI-Shared');
    const kept = path.join(dataDir, 'kept-comfyui');
    fs.mkdirSync(path.join(shared, 'models'), { recursive: true });
    fs.mkdirSync(kept, { recursive: true });
    const record = (modelsDir: string, seenAt: number) => ({
      identity: modelsDir,
      seenAt,
      info: { modelPathFiles: [] },
      modelsDir,
    });
    // Another machine's paths never count, even when they happen to exist here.
    store.noteComfyInstall('http://192.168.1.9:8188', record(path.join(kept, 'models'), 5));
    delete process.env.COMFYUI_ROOT;
    assert.deepEqual(resolveComfyUiRoot(), { root: null, source: 'none' });

    store.noteComfyInstall('http://127.0.0.1:8188', record(path.join(shared, 'models'), 6));
    assert.deepEqual(resolveComfyUiRoot(), { root: path.resolve(shared), source: 'detected' });
    // A COMFYUI_ROOT naming a removed install gives way to the one found.
    process.env.COMFYUI_ROOT = path.join(dataDir, 'removed-comfyui');
    assert.deepEqual(resolveComfyUiRoot(), { root: path.resolve(shared), source: 'detected' });
    // One that exists is the operator's choice and wins.
    process.env.COMFYUI_ROOT = kept;
    assert.deepEqual(resolveComfyUiRoot(), { root: path.resolve(kept), source: 'env' });
    delete process.env.COMFYUI_ROOT;
  });

  it('copies the previous install’s folders without overwriting anything', async () => {
    const { comfyInstallJob, startCopyFoldersJob } = await import('./install-server');
    const from = fs.mkdtempSync(path.join(os.tmpdir(), 'old-input-'));
    const to = fs.mkdtempSync(path.join(os.tmpdir(), 'new-input-'));
    fs.mkdirSync(path.join(from, 'sub'));
    fs.writeFileSync(path.join(from, 'cast-plate.png'), 'old');
    fs.writeFileSync(path.join(from, 'sub', 'pose.png'), 'old-pose');
    fs.writeFileSync(path.join(from, 'Castcut_00001_.png'), 'old-render');
    fs.writeFileSync(path.join(to, 'Castcut_00001_.png'), 'new-render');
    const job = startCopyFoldersJob([{ from, to }]);
    for (let i = 0; i < 100 && comfyInstallJob(job.id)?.status === 'running'; i += 1) {
      await new Promise(resolve => setTimeout(resolve, 10));
    }
    const done = comfyInstallJob(job.id)!;
    assert.equal(done.status, 'completed');
    assert.equal(done.copied, 2);
    assert.equal(done.skipped, 1);
    assert.equal(fs.readFileSync(path.join(to, 'sub', 'pose.png'), 'utf8'), 'old-pose');
    // The new install's own render, same name, is kept.
    assert.equal(fs.readFileSync(path.join(to, 'Castcut_00001_.png'), 'utf8'), 'new-render');
    fs.rmSync(from, { recursive: true, force: true });
    fs.rmSync(to, { recursive: true, force: true });
  });

  it('puts the app’s kept pictures into ComfyUI, only the ones it lacks', async () => {
    const { keepComfyInputCopy } = await import('./input-store-server');
    const { comfyInstallJob, startRestorePicturesJob } = await import('./install-server');
    keepComfyInputCopy({ filename: 'restore-has.png' }, new Uint8Array([1]));
    keepComfyInputCopy({ filename: 'restore-lacks.png' }, new Uint8Array([2]));
    const uploaded: string[] = [];
    const fetchImpl = async (url: string, init?: RequestInit) => {
      if (init?.method === 'HEAD') {
        const name = new URL(url).searchParams.get('filename');
        return new Response(null, { status: name === 'restore-lacks.png' ? 404 : 200 });
      }
      const form = init?.body as FormData;
      uploaded.push((form.get('image') as File).name);
      return Response.json({ name: 'ok' });
    };
    const job = startRestorePicturesJob('http://comfy', fetchImpl);
    for (let i = 0; i < 100 && comfyInstallJob(job.id)?.status === 'running'; i += 1) {
      await new Promise(resolve => setTimeout(resolve, 10));
    }
    assert.equal(comfyInstallJob(job.id)?.status, 'completed');
    assert.ok(uploaded.includes('restore-lacks.png'));
    assert.ok(!uploaded.includes('restore-has.png'));
  });
});
